// Builds content/UPLOAD-LONG.md: publishing plan for the long videos, with YouTube chapter timestamps,
// descriptions, tags, pinned comments and the thumbnail file for each.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const long = JSON.parse(fs.readFileSync(path.join(root, 'src/generated/long.json'), 'utf8'));
const SITE = 'https://thesignsandmeanings.com';

// Publish date/time (US Eastern), site page, pinned comment, related Short for the end screen.
const meta = {
  'L1-number-superstitions': {
    when: 'Sun 2026-10-25, 12:00 ET',
    link: '/angel-numbers/',
    pinned: 'Which number do you avoid, and which one do you chase? 👇 (Bonus: did you know about Friday the 17th?)',
    related: 'f01-fourth-floor',
    playlist: 'Secret Life of Numbers',
  },
  'L2-angel-numbers-111-999': {
    when: 'Wed 2026-10-28, 12:00 ET',
    link: '/angel-numbers/',
    pinned: 'Which number keeps showing up for you lately? Reply with it and I\'ll tell you how it\'s traditionally read 👇',
    related: 'f06-who-invented-angel-numbers',
    playlist: 'Angel Numbers',
  },
  'L4-bedtime-moon-stories': {
    when: 'Fri 2026-10-30, 20:00 ET',
    link: '/moon/',
    pinned: 'Sleep well 🌙 Which story did you fall asleep to? Tell me in the morning.',
    related: 'p02-pick-a-moon',
    playlist: 'Sleep Stories',
  },
  'L3-full-moons-2027': {
    when: 'Sun 2026-11-01, 12:00 ET',
    link: '/moon/',
    pinned: 'Which full moon is your birthday moon? 🌕 Mine is the Harvest Moon.',
    related: 'm01-birth-month-moon',
    playlist: 'Moon Calendar',
  },
};

const stamp = (s) => {
  const t = Math.floor(s);
  const h = Math.floor(t / 3600);
  const m = Math.floor((t % 3600) / 60);
  const sec = String(t % 60).padStart(2, '0');
  return h ? `${h}:${String(m).padStart(2, '0')}:${sec}` : `${m}:${sec}`;
};
const mmss = (s) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;

const out = [
  '# Long-form videos: upload sheet',
  '',
  'Generated by `node scripts/upload-long.mjs`. Upload in this order. Times are US Eastern (Poland = +5 h until 1 Nov, then +6 h).',
  '',
  '**Every upload:** Made for kids → No · Category → Education · Altered or synthetic content → No (illustrations, AI narrator',
  'that does not imitate a real person) · Upload the thumbnail `out/<id>.thumb.jpg` · Paste the chapters exactly as below',
  '(the first must be 0:00, so YouTube shows chapters in the progress bar) · End screen: "Best for viewer" video + Subscribe,',
  'placed in the free middle area of the last 12–14 s · Pin the comment right after publishing.',
  '',
  'Shorts → longs: after each long goes live, set it as **Related video** on the matching Short (the column below).',
  '',
];

for (const [id, m] of Object.entries(meta)) {
  const L = long[id];
  const script = JSON.parse(fs.readFileSync(path.join(root, 'content/long', `${id}.json`), 'utf8'));
  if (!L) continue;
  const label = (c) => {
    const v = L.segments.find((s) => s.chapter === c.index)?.v;
    return v?.type === 'chapter' && v.kicker && v.kicker !== 'Before we start' ? `${v.kicker}: ${c.title}` : c.title;
  };
  const chapters = L.chapters.map((c, i) => `${stamp(i === 0 ? 0 : c.start)} ${label(c)}`).join('\n');
  const ready = fs.existsSync(path.join(root, 'out', `${id}.mp4`));
  const hashtags = script.tags.slice(0, 3).map((t) => '#' + t.replace(/[^a-z0-9]/gi, ''));
  const desc = [
    script.description,
    '',
    `More: ${SITE}${m.link}`,
    '',
    'Chapters',
    chapters,
    '',
    L.mode === 'sleep'
      ? 'Narration ends around ' + stamp(L.segments[L.segments.length - 1].start + L.segments[L.segments.length - 1].len) + ', followed by a few minutes of quiet music and a dark screen.'
      : 'Symbolism is presented as tradition and folklore, not as prediction. Historical facts are checked against published sources.',
    '',
    hashtags.join(' '),
  ].join('\n');
  out.push(
    `## ${id} ${ready ? '✅' : '⏳'} · ${mmss(L.duration)} · ${m.when}`,
    '',
    `**File:** out/${id}.mp4 · **Thumbnail:** out/${id}.thumb.jpg · **Playlist:** ${m.playlist} · **Related Short:** ${m.related}`,
    '',
    `**Title:** ${script.title}`,
    '',
    '**Description:**',
    '```',
    desc,
    '```',
    '',
    `**Tags:** ${script.tags.join(', ')}`,
    '',
    `**Pinned comment:** ${m.pinned}`,
    '',
  );
}

fs.writeFileSync(path.join(root, 'content/UPLOAD-LONG.md'), out.join('\n'));
console.log('content/UPLOAD-LONG.md');
