// Builds content/UPLOAD.md: publishing order, titles, descriptions with the matching site page, hashtags, pinned comments.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const series = JSON.parse(fs.readFileSync(path.join(root, 'content/series-1.json'), 'utf8'));
const timings = JSON.parse(fs.readFileSync(path.join(root, 'src/generated/timings.json'), 'utf8'));
const SITE = 'https://thesignsandmeanings.com';

const links = {
  'f01-fourth-floor': '/angel-numbers/444/',
  'f02-lucky-eight': '/angel-numbers/888/',
  'f03-watch-1010': '/mirror-hours/1010/',
  'f04-apollo-13': '/angel-numbers/1313/',
  'f05-616': '/angel-numbers/666/',
  'f06-who-invented-angel-numbers': '/angel-numbers/',
  'f07-why-1111-follows-you': '/angel-numbers/1111/',
  'f08-cat-zodiac': '/chinese-zodiac/',
  'f09-seven-day-week': '/angel-numbers/777/',
  'f10-birthstones-1912': '/birthstones/',
  'p01-pick-a-door': '/angel-numbers/123/',
  'p02-pick-a-moon': '/moon/',
  'p03-pick-a-crystal': '/crystals/',
  'p04-pick-a-time': '/mirror-hours/',
  'm01-birth-month-moon': '/moon/',
  'm02-birth-month-birthstone': '/birthstones/',
  'm03-life-path-20-seconds': '/life-path-number/',
  'm04-chinese-zodiac-year': '/chinese-zodiac/',
  't01-11-11-day': '/mirror-hours/1111/',
  't02-closest-full-moon-2026': '/moon/cold-moon/',
};

// Publishing order: alternate formats, strongest hooks first. Times are US Eastern.
const plan = [
  ['f01-fourth-floor', 'p01-pick-a-door'],
  ['f05-616', 'm01-birth-month-moon'],
  ['f02-lucky-eight', 'p02-pick-a-moon'],
  ['f03-watch-1010', 'm03-life-path-20-seconds'],
  ['f04-apollo-13', 'p03-pick-a-crystal'],
  ['f09-seven-day-week', 'm02-birth-month-birthstone'],
  ['f10-birthstones-1912', 'p04-pick-a-time'],
  ['f06-who-invented-angel-numbers', 'f08-cat-zodiac'],
  ['f07-why-1111-follows-you', 'm04-chinese-zodiac-year'],
];

const lifePath = fs
  .readdirSync('/home/user/signs-meanings/src/content/lifepath/en')
  .map((f) => JSON.parse(fs.readFileSync(path.join('/home/user/signs-meanings/src/content/lifepath/en', f), 'utf8')))
  .sort((a, b) => Number(a.n) - Number(b.n));

const byId = Object.fromEntries(series.shorts.map((s) => [s.id, s]));
const ready = (id) => fs.existsSync(path.join(root, 'out', `${id}.mp4`));
const card = (id) => {
  const s = byId[id];
  const url = SITE + (links[id] ?? '/');
  const desc = `${s.description}\n\nFull meaning: ${url}\n\n${s.hashtags.join(' ')}`;
  return [
    `### ${id} ${ready(id) ? '✅ out/' + id + '.mp4' : '⏳ waits for images'} · ${timings[id].duration.toFixed(0)} s`,
    '',
    `**Title:** ${s.title}`,
    '',
    '**Description:**',
    '```',
    desc,
    '```',
    `**Pinned comment:** ${s.pinnedComment}`,
    '',
  ].join('\n');
};

const out = ['# Upload sheet — series 1', '', 'Generated by `scripts/upload-sheet.mjs`. Times: 9:00 and 18:00 US Eastern.', ''];
const start = new Date('2026-10-24T12:00:00Z');
plan.forEach((pair, d) => {
  const day = new Date(start.getTime() + d * 864e5).toISOString().slice(0, 10);
  out.push(`## Day ${d + 1} — ${day}`, '');
  pair.forEach((id, i) => out.push(`*${i === 0 ? '9:00 ET' : '18:00 ET'}*`, '', card(id)));
});
out.push('## Timely', '');
out.push('*Publish 2026-11-10, 18:00 ET (people search on the evening before and the morning of 11/11)*', '', card('t01-11-11-day'));
out.push('*Publish 2026-12-22, 18:00 ET*', '', card('t02-closest-full-moon-2026'));
out.push('## Cheat sheet for replies on m03 (life path)', '', ...lifePath.map((l) => `- **${l.n}** — ${l.tagline}`), '');
fs.writeFileSync(path.join(root, 'content/UPLOAD.md'), out.join('\n'));
console.log('content/UPLOAD.md');
